import { afterEach, describe, expect, it, vi } from 'vitest'
import { createLiveSearch } from './liveSearch'

afterEach(() => { vi.useRealTimers() })

describe('live administrator user search', () => {
  it('invalidates previous work immediately and searches only the latest input after 300 ms', () => {
    vi.useFakeTimers()
    const run = vi.fn(); const invalidate = vi.fn()
    const search = createLiveSearch(run, invalidate)
    search.update('q')
    vi.advanceTimersByTime(150)
    search.update('qa_main')
    expect(invalidate.mock.calls.map(call => call[0])).toEqual(['q', 'qa_main'])
    vi.advanceTimersByTime(299)
    expect(run).not.toHaveBeenCalled()
    vi.advanceTimersByTime(1)
    expect(run).toHaveBeenCalledExactlyOnceWith('qa_main')
  })
  it('restores the full directory immediately when input is cleared and cancels pending searches', () => {
    vi.useFakeTimers()
    const run = vi.fn()
    const search = createLiveSearch(run, vi.fn())
    search.update('admin')
    search.update('  ')
    expect(run).toHaveBeenCalledExactlyOnceWith('')
    vi.runAllTimers()
    expect(run).toHaveBeenCalledTimes(1)
  })
  it('waits for Chinese composition to finish and ignores Enter during composition', () => {
    vi.useFakeTimers()
    const run = vi.fn()
    const search = createLiveSearch(run, vi.fn())
    search.update('q')
    search.startComposition()
    search.update('qing')
    search.flush('qing')
    vi.advanceTimersByTime(500)
    expect(run).not.toHaveBeenCalled()
    search.endComposition('青禾')
    vi.advanceTimersByTime(300)
    expect(run).toHaveBeenCalledExactlyOnceWith('青禾')
  })
  it('supports immediate Enter submission without a duplicate delayed request', () => {
    vi.useFakeTimers()
    const run = vi.fn()
    const search = createLiveSearch(run, vi.fn())
    search.update(' admin ')
    search.flush(' admin ')
    expect(run).toHaveBeenCalledExactlyOnceWith('admin')
    vi.runAllTimers()
    expect(run).toHaveBeenCalledTimes(1)
  })
  it('clears pending work on account reset or component disposal', () => {
    vi.useFakeTimers()
    const run = vi.fn()
    const search = createLiveSearch(run, vi.fn())
    search.update('old-account')
    search.reset()
    vi.runAllTimers()
    expect(run).not.toHaveBeenCalled()
    search.update('new-account')
    search.dispose()
    search.update('disposed')
    vi.runAllTimers()
    expect(run).not.toHaveBeenCalled()
  })
})
